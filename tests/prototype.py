from playwright.sync_api import sync_playwright
import json

results=[]
def ok(name):
    results.append(name)
    print('PASS',name)

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[]
    page.on('pageerror',lambda e: errors.append(str(e)))
    page.goto('http://localhost:4200/dashboard')
    page.wait_for_load_state('networkidle')
    page.evaluate('localStorage.clear()')
    page.reload()
    page.get_by_role('heading',name='Bonjour, Alexandre.').wait_for()
    routes=['students','families','classes','teachers','subjects','schedule','lessons','grades','reports','exams','attendance','discipline','payments','fees','cash','messages','documents','library','transport','settings','years','rooms','permissions','imports','audit','tenants','subscriptions','support','health','login','portal']
    for route in routes:
        page.goto('http://localhost:4200/'+route)
        page.locator('main h1').first.wait_for()
        assert page.locator('main').inner_text().strip()
        assert not page.evaluate('document.documentElement.scrollWidth>innerWidth'),route+' overflow'
    ok('31 écrans : rendu desktop sans débordement')
    page.goto('http://localhost:4200/students')
    page.get_by_role('button',name='Inscrire un élève',exact=True).click()
    dialog=page.get_by_role('dialog')
    dialog.locator('input[name="name"]').fill('Alice Test')
    dialog.locator('input[name="field1"]').fill('Parent Test')
    dialog.get_by_role('button',name='Créer la fiche').click()
    page.locator('button.name-cell').filter(has_text='Alice Test').wait_for()
    page.reload()
    page.locator('button.name-cell').filter(has_text='Alice Test').wait_for()
    page.locator('.table-search input').fill('Alice Test')
    assert page.locator('tbody tr').count()==1
    page.locator('button.name-cell').filter(has_text='Alice Test').click()
    page.locator('.drawer h2').wait_for()
    page.locator('.drawer').get_by_role('button',name='Modifier la fiche').click()
    page.get_by_role('dialog').locator('input[name="name"]').fill('Alice Test Modifiée')
    page.get_by_role('dialog').get_by_role('button',name='Enregistrer').click()
    page.locator('button.name-cell').filter(has_text='Alice Test Modifiée').wait_for()
    ok('Inscription, persistance, recherche et modification du dossier')
    page.goto('http://localhost:4200/grades')
    page.get_by_label('Note de Emma Laurent',exact=True).fill('')
    page.get_by_role('button',name='Valider la saisie').click()
    assert 'Validation bloquée' in page.get_by_role('status').inner_text()
    page.get_by_label('Note de Emma Laurent',exact=True).fill('18')
    page.get_by_role('button',name='Valider la saisie').click()
    page.get_by_role('dialog').get_by_role('button',name='Confirmer').click()
    assert page.get_by_label('Note de Emma Laurent',exact=True).is_disabled()
    page.get_by_role('button',name='Correction motivée').click()
    page.get_by_role('dialog').locator('textarea').fill('Correction du barème de démonstration')
    page.get_by_role('button',name='Déverrouiller la démonstration').click()
    assert page.get_by_label('Note de Emma Laurent',exact=True).is_enabled()
    ok('Notes : contrôle des manquants, validation, verrouillage et correction motivée')
    page.goto('http://localhost:4200/reports')
    page.get_by_role('button',name='Prévisualiser un bulletin').click()
    assert 'Σ' in page.get_by_role('dialog').inner_text()
    page.get_by_role('button',name='Fermer la fenêtre',exact=True).click()
    page.get_by_role('button',name='Valider les bulletins').click()
    page.get_by_role('dialog').get_by_role('button',name='Confirmer').click()
    page.get_by_role('button',name='Publier les bulletins').click()
    page.get_by_role('dialog').get_by_role('button',name='Confirmer').click()
    assert page.locator('.report-layout').get_by_text('Publié',exact=True).count()>0
    ok('Bulletins : aperçu, validation et publication simulée')
    page.goto('http://localhost:4200/schedule')
    page.get_by_role('button',name='Générer un planning').click()
    page.get_by_role('button',name='Créer la proposition fictive').click()
    assert 'Brouillon' in page.locator('.planning-status').inner_text()
    page.get_by_role('button',name='Publier',exact=True).click()
    page.get_by_role('dialog').get_by_role('button',name='Confirmer').click()
    assert 'Publié' in page.locator('.planning-status').inner_text()
    ok('Planning : proposition et publication simulées')
    page.goto('http://localhost:4200/payments')
    page.get_by_role('button',name='Enregistrer un paiement').click()
    page.get_by_role('dialog').locator('input[name="amount"]').fill('150')
    page.get_by_role('button',name='Confirmer et créer le reçu').click()
    assert '150 €' in page.get_by_role('dialog').inner_text()
    page.get_by_role('button',name='Fermer la fenêtre',exact=True).click()
    ok('Paiement fictif et reçu unique local')
    page.goto('http://localhost:4200/messages')
    page.get_by_role('button',name='Nouvelle annonce').click()
    page.get_by_role('dialog').locator('input[name="name"]').fill('Annonce Test')
    page.get_by_role('dialog').locator('textarea').fill('Message fictif pour vérifier le parcours.')
    page.get_by_role('button',name='Enregistrer le brouillon').click()
    card=page.locator('.message-grid .panel').filter(has_text='Annonce Test')
    card.get_by_role('button',name='Publier').click()
    page.get_by_role('button',name='Confirmer la publication').click()
    assert 'Publié' in card.inner_text()
    ok('Communication : brouillon et publication sans envoi réel')
    page.get_by_label('Profil de démonstration',exact=True).select_option('Parent')
    page.get_by_role('heading',name='Bonjour, Sophie.').wait_for()
    assert page.locator('.nav-item').filter(has_text='Élèves & inscriptions').count()==0
    page.locator('nav a[href="/grades"]').click()
    assert page.locator('tbody tr').count()==1
    assert page.get_by_label('Note de Emma Laurent',exact=True).is_disabled()
    assert page.get_by_label('Note de Emma Laurent',exact=True).input_value()=='16'
    page.locator('nav a[href="/schedule"]').click()
    assert page.get_by_label('Vue du planning').locator('option').count()==1
    page.get_by_label('Profil de démonstration',exact=True).select_option('Plateforme SaaS')
    assert page.locator('nav a[href="/tenants"]').count()==1
    ok('Portail parent filtré et lecture seule ; navigation SaaS')
    page.get_by_label('Profil de démonstration',exact=True).select_option('Direction')
    page.goto('http://localhost:4200/imports')
    page.locator('input[type="file"]').set_input_files({'name':'test.csv','mimeType':'text/csv','buffer':b'nom;classe;responsable\nImport Test;4e A;Parent Import\nInvalide;;Parent'})
    page.get_by_role('button',name='Confirmer les lignes valides').wait_for()
    assert 'Rejeté' in page.locator('.import-preview').inner_text()
    page.get_by_role('button',name='Confirmer les lignes valides').click()
    page.locator('button.name-cell').filter(has_text='Import Test').wait_for()
    ok('Import CSV : prévalidation, rejet et insertion locale')
    page.goto('http://localhost:4200/dashboard')
    page.screenshot(path='/home/user/scolia-dashboard.png',full_page=True,animations="disabled")
    mobile=browser.new_page(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
    mobile.on('pageerror',lambda e: errors.append(str(e)))
    for route in ['dashboard','students','schedule','grades','reports','attendance','payments','messages','settings','portal']:
        mobile.goto('http://localhost:4200/'+route)
        mobile.locator('main h1').first.wait_for()
        assert not mobile.evaluate('document.documentElement.scrollWidth>innerWidth'),route+' mobile overflow'
    mobile.goto('http://localhost:4200/dashboard')
    mobile.screenshot(path='/home/user/scolia-mobile.png',full_page=True,animations="disabled")
    mobile.get_by_role('button',name='Ouvrir le menu').click()
    mobile.locator('nav a[href="/students"]').click()
    assert not mobile.locator('.sidebar').evaluate('(el)=>el.classList.contains("open")')
    ok('10 écrans mobile sans débordement et menu escamotable')
    assert not errors,errors
    ok('Aucune erreur JavaScript pendant les parcours')
    page.evaluate('localStorage.clear()')
    browser.close()

with open('/home/user/scolia/tests/results.json','w') as f:json.dump({'passed':results,'errors':errors},f,ensure_ascii=False,indent=2)